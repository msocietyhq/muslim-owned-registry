export type Messages = Omit<(typeof messages)["en"], "htmlLang"> & { htmlLang: string };

export function isLang(value: string | undefined | null): value is Lang {
  return value === "en" || value === "ms" || value === "zh" || value === "ta";
}

export function copy(lang: Lang): Messages {
  return messages[lang] as unknown as Messages;
}

export function dateLocale(lang: Lang) {
  if (lang === "ms") return "ms-SG";
  if (lang === "zh") return "zh-SG";
  if (lang === "ta") return "ta-SG";
  return "en-SG";
}

export function statusLabel(lang: Lang, status: string) {
  const labels = copy(lang).status as Record<string, string>;
  return labels[status] || status.replace(/_/g, " ");
}
